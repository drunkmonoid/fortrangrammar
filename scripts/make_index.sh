#!/usr/bin/env bash
# Regenerate INDEX.md: one line per example, taken from each file's header
# line "! NN_name.f90 - description" (or the first comment of a build.sh
# directory's main source).
# Usage: scripts/make_index.sh > INDEX.md
set -euo pipefail
root="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
cd "$root"
shopt -s nullglob

echo "# Index of Examples"
echo
echo "Generated by \`scripts/make_index.sh\` from the header line of every example."
for chapter in [0-9][0-9]-*/; do
  chapter="${chapter%/}"
  title="$(sed -n '1s/^# //p' "$chapter/README.md")"
  echo
  echo "## [$title]($chapter/)"
  echo
  echo "| Example | Description |"
  echo "|---|---|"
  # Source files are sorted by name so 01_*.f precedes 02_*.f90. Markdown
  # notes and multi-file directories keep their previous position, after
  # the sources.
  sources=("$chapter"/*.f90 "$chapter"/*.F90 "$chapter"/*.f)
  if ((${#sources[@]})); then
    mapfile -t sources < <(printf '%s\n' "${sources[@]}" | sort)
  fi
  for f in "${sources[@]}" "$chapter"/*.md "$chapter"/*.sh "$chapter"/*/; do
    name="$(basename "$f")"
    [[ $name == README.md ]] && continue
    if [[ -d $f ]]; then
      desc="multi-file example ($(ls "$f" | grep -E '\.(f90|F90|f|c|h|toml|txt)$|Makefile|CMakeLists' | tr '\n' ' ' | sed 's/ $//'))"
      name="$name/"
    elif [[ $name == *.md ]]; then
      desc="$(sed -n '1s/^# //p' "$f")"
    elif [[ $name == *.sh ]]; then
      desc="$(grep -m1 -E '^# ' "$f" | sed 's/^# //')"
    else
      desc="$(grep -m1 -E "^! $name - " "$f" | sed "s/^! $name - //")"
    fi
    echo "| [$name]($chapter/$name) | ${desc//|/\\|} |"
  done
done
